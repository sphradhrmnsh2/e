# -*- coding: utf-8 -*-
"""
یک مثال ساده از یادگیری ماشین
پیش‌بینی قیمت خانه بر اساس متراژ و تعداد اتاق
"""

import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, r2_score

# ==========================================
# ۱. ساختن دیتاست نمونه
# ==========================================
data = {
    "متراژ": [50, 60, 70, 80, 90, 100, 110, 120, 130, 140, 150, 160],
    "تعداد_اتاق": [1, 1, 2, 2, 2, 3, 3, 3, 4, 4, 4, 5],
    "قیمت": [2000, 2400, 2800, 3200, 3600, 4000, 4400, 4800, 5200, 5600, 6000, 6400]
}

df = pd.DataFrame(data)
print("📊 دیتاست ما:")
print(df)
print("-" * 50)

# ==========================================
# ۲. جدا کردن ویژگی‌ها (X) و هدف (y)
# ==========================================
X = df[["متراژ", "تعداد_اتاق"]]   # ورودی‌ها
y = df["قیمت"]                     # خروجی که می‌خوایم پیش‌بینی کنیم

# ==========================================
# ۳. تقسیم به داده آموزش و تست
# ==========================================
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.25, random_state=42
)
print(f"✅ داده آموزش: {len(X_train)} نمونه")
print(f"✅ داده تست: {len(X_test)} نمونه")
print("-" * 50)

# ==========================================
# ۴. ساختن و آموزش مدل
# ==========================================
model = LinearRegression()
model.fit(X_train, y_train)
print("🤖 مدل با موفقیت آموزش دید!")
print("-" * 50)

# ==========================================
# ۵. ارزیابی مدل
# ==========================================
y_pred = model.predict(X_test)

print("📈 نتایج ارزیابی:")
print(f"   MAE (میانگین خطا): {mean_absolute_error(y_test, y_pred):.2f}")
print(f"   R² Score: {r2_score(y_test, y_pred):.4f}")
print("-" * 50)

# ==========================================
# ۶. پیش‌بینی برای یک خانه جدید
# ==========================================
new_house = pd.DataFrame({
    "متراژ": [105],
    "تعداد_اتاق": [3]
})

predicted_price = model.predict(new_house)[0]
print(f"🏠 خانه با ۱۰۵ متراژ و ۳ اتاق:")
print(f"   💰 قیمت پیش‌بینی شده: {predicted_price:,.0f} واحد")